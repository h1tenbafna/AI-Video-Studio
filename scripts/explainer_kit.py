#!/usr/bin/env python
"""Helpers for the /explainer skill (blueprint-isometric theme, from ai-compute-business-explainer).

  python scripts/explainer_kit.py check                 # read-only: music track, Kokoro voice, ffmpeg, node
  python scripts/explainer_kit.py new <project_id>      # copy the episode template to remotion-composer/src/explainers/<project_id>/
  python scripts/explainer_kit.py words <project_id> [--transcript PATH]
                                                        # Whisper transcript -> episode words.ts (caption timings)

Writes only inside remotion-composer/src/explainers/<project_id>/. Never downloads anything.
"""
import hashlib, json, os, platform, shutil, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXPL = ROOT / "remotion-composer" / "src" / "explainers"
TEMPLATE = EXPL / "_template"
MUSIC = ROOT / "music_library" / "pixabay_calm_ambient_tech.mp3"
MUSIC_SHA = "417375d449a46ba4588597291ed625e810b5502cfbd396f0a6f752b93cf8134f"
MUSIC_SECONDS = 113.7
VENV_PY = ROOT / ".venv" / ("Scripts/python.exe" if os.name == "nt" else "bin/python")


def _duration(p):
    try:
        out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(p)],
                             capture_output=True, text=True, timeout=30).stdout.strip()
        return float(out)
    except Exception:
        return None


def cmd_check():
    ok = True
    print(f"platform: {platform.system()} {platform.machine()}")
    # music
    if MUSIC.exists():
        sha = hashlib.sha256(MUSIC.read_bytes()).hexdigest()
        d = _duration(MUSIC)
        if sha == MUSIC_SHA:
            print(f"music: OK, exact same file ({MUSIC.name})")
        elif d and abs(d - MUSIC_SECONDS) < 1.5:
            print(f"music: OK-ish, same length ({d:.1f} s) but different bytes; likely the same track re-encoded. Tell the user.")
        else:
            print(f"music: MISMATCH ({d} s, sha {sha[:12]}). Not the theme track. STOP and ask the user.")
            ok = False
    else:
        ok = False
        print("music: MISSING music_library/pixabay_calm_ambient_tech.mp3\n"
              "  The user downloads it by hand (free): pixabay.com/music, search \"Ambient Calm\" by AtlasAudio (about 1:54),\n"
              "  save as music_library/pixabay_calm_ambient_tech.mp3, then re-run this check. Do NOT scrape or substitute.")
    # tools
    for exe in ("ffmpeg", "ffprobe", "node", "npx"):
        print(f"{exe}: {'OK' if shutil.which(exe) else 'MISSING'}")
        ok &= bool(shutil.which(exe))
    # Kokoro
    if VENV_PY.exists():
        r = subprocess.run([str(VENV_PY), "-c", "import kokoro_onnx"], capture_output=True, text=True)
        print(f"kokoro-onnx in .venv: {'OK' if r.returncode == 0 else 'MISSING (pip install kokoro-onnx into .venv; ask first)'}")
        ok &= r.returncode == 0
    else:
        print(f"venv: MISSING {VENV_PY}")
        ok = False
    print(f"voice command: HYPERFRAMES_PYTHON={VENV_PY} npx hyperframes tts \"<text>\" --voice af_heart -o <out.wav>")
    print("  (first use downloads the Kokoro model, about 600 MB, to ~/.cache/hyperframes)")
    print("READY" if ok else "NOT READY: fix the items above before the assets stage")
    return 0 if ok else 1


def cmd_new(pid):
    dst = EXPL / pid
    if dst.exists():
        print(f"exists, not touching: {dst.relative_to(ROOT)}")
        return 1
    shutil.copytree(TEMPLATE, dst)
    print(f"created {dst.relative_to(ROOT)} (index.tsx, scenes.tsx, timing.ts, words.ts)")
    print(f"render: cd remotion-composer && npx remotion render src/explainers/{pid}/index.tsx Episode "
          f"../projects/{pid}/renders/video_silent.mp4 --concurrency 2 --crf 18")
    return 0


def cmd_words(pid, transcript=None):
    dst = EXPL / pid / "words.ts"
    if not dst.parent.exists():
        print(f"run `new {pid}` first")
        return 1
    src = Path(transcript) if transcript else ROOT / "projects" / pid / "assets" / "audio" / "transcript" / "narration_timeline_transcript.json"
    data = json.loads(src.read_text(encoding="utf-8"))
    if isinstance(data, list):  # already [{word,startMs,endMs}]
        words = [{"word": w["word"].strip(), "startMs": int(w["startMs"]), "endMs": int(w["endMs"])} for w in data]
    else:
        raw = data.get("word_timestamps") or [w for s in data.get("segments", []) for w in s.get("words", [])]
        words = [{"word": w["word"].strip(), "startMs": round(w["start"] * 1000), "endMs": round(w["end"] * 1000)}
                 for w in raw if w.get("word", "").strip()]
    body = ",\n".join("  " + json.dumps(w) for w in words)
    dst.write_text("// GENERATED by scripts/explainer_kit.py words from " + src.name + ". Fix misheard words by hand.\n"
                   'import type { W } from "../../blueprint/ui";\nexport const WORDS: W[] = [\n' + body + "\n];\n",
                   encoding="utf-8")
    print(f"wrote {len(words)} words to {dst.relative_to(ROOT)}; check names/numbers against the script")
    return 0


if __name__ == "__main__":
    a = sys.argv[1:]
    if not a:
        print(__doc__); sys.exit(0)
    if a[0] == "check":
        sys.exit(cmd_check())
    if a[0] == "new" and len(a) >= 2:
        sys.exit(cmd_new(a[1]))
    if a[0] == "words" and len(a) >= 2:
        t = a[a.index("--transcript") + 1] if "--transcript" in a else None
        sys.exit(cmd_words(a[1], t))
    print(__doc__); sys.exit(2)
